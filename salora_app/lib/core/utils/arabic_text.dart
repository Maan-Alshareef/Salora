  static String tr(String? text) {
    if (text == null) return '';
    final trimmed = text.trim();
    if (trimmed.isEmpty) return trimmed;
    final direct = values[trimmed];
    if (direct != null) return direct;

    var result = text;
    values.forEach((en, ar) {
      result = result.replaceAll(en, ar);
    });
    return result;
  }

  static List<String> list(Iterable<String> items) =>
      items.map(tr).where((e) => e.trim().isNotEmpty).toList();
}
